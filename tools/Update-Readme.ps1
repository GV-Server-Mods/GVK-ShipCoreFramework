<#
.SYNOPSIS
    Rebuilds the grid class table in README.md from the core XML files, so it can't drift.

.DESCRIPTION
    Reads every Content/Data/*_core.xml (one per core beacon) and rewrites the text between
        <!-- GENERATED:grid-classes --> ... <!-- /GENERATED:grid-classes -->
    in README.md. Everything outside the markers is left alone.

.PARAMETER Check
    Report whether the README table is out of date without writing it (exit code 1 if it is).
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$readmePath = Join-Path $root 'README.md'

function Fmt([string]$v, [string]$none = 'none') {
    if ([string]::IsNullOrEmpty($v) -or $v -eq '-1') { return $none }
    if ($v -match '^\d+$') { return ([int]$v).ToString('N0', [Globalization.CultureInfo]::InvariantCulture) }
    return $v
}

$rows = foreach ($f in Get-ChildItem (Join-Path $root 'Content\Data') -Filter *_core.xml) {
    $core = ([xml][IO.File]::ReadAllText($f.FullName)).ShipCore
    $limits = @{}
    foreach ($l in $core.BlockLimits) { $limits[[string]$l.Name] = [string]$l.MaxCount }
    $npc = [string]$core.UniqueName -match 'NPC'
    [pscustomobject]@{
        Name = [string]$core.UniqueName; Subtype = [string]$core.SubtypeId; Npc = $npc
        Blocks = [string]$core.MaxBlocks; Mobility = [string]$core.MobilityType
        MP = $limits['MP Mobility Points']; UP = $limits['UP Utility Points']
        Speed = [string]$core.SpeedModifiers.MaxSpeed; Boost = [string]$core.SpeedModifiers.MaxBoost
        Interior = $limits['H Interior Turrets']; Salvage = $limits['H Salvage Turrets']
    }
}
$lines = @('| Core | Beacon subtype | Max blocks | Mobility | MPs | UPs | Speed | Boost | Interior turrets | Salvage turrets |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
foreach ($r in $rows | Sort-Object @{ Expression = { $_.Npc } }, @{ Expression = { [int]$_.Blocks }; Descending = $true }, Name) {
    $lines += "| $($r.Name) | ``$($r.Subtype)`` | $(Fmt $r.Blocks 'no limit') | $($r.Mobility) | $(Fmt $r.MP) | $(Fmt $r.UP) | $($r.Speed) | $($r.Boost) | $(Fmt $r.Interior) | $(Fmt $r.Salvage) |"
}

$text = [IO.File]::ReadAllText($readmePath)
$nl = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
$pattern = '(?s)(<!-- GENERATED:grid-classes -->).*?(<!-- /GENERATED:grid-classes -->)'
if ($text -notmatch $pattern) { Write-Warning 'README.md has no GENERATED:grid-classes markers'; exit 1 }
$block = $nl + '<!-- Generated by tools/Update-Readme.ps1 from the core XML files. Do not edit by hand. -->' + $nl +
    '*Generated by `tools/Update-Readme.ps1` from the `*_core.xml` files. To change it, edit those files.*' + $nl + $nl + ($lines -join $nl) + $nl
$new = [regex]::Replace($text, $pattern, { param($m) $m.Groups[1].Value + $block + $m.Groups[2].Value })
if ($new -ceq $text) { Write-Output 'README table is up to date.'; exit 0 }
if ($Check) { Write-Output 'README table is out of date.'; exit 1 }
[IO.File]::WriteAllText($readmePath, $new, (New-Object Text.UTF8Encoding($false)))
Write-Output 'README table regenerated.'
